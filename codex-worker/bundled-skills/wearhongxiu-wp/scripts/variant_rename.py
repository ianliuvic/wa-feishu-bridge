def state(client: Client, collector: Collector, identifier: str) -> dict:
    resolved = resolve_wordpress(client, identifier)
    source = collector_product(collector, resolved.get("sku"))
    detail_id = source.get("product_detail_id")
    colors = (resolved.get("catalog") or {}).get("colors", {}).get("colors") or []
    overrides = (collector.request("GET", f"/api/product-details/{detail_id}/option-overrides")
                 or {}).get("overrides") or []
    # What the collector currently matches each colour on, before any new rename.
    current = preview_payload(collector, detail_id, resolved)
    return {
        "resolved": resolved,
        "collector": source,
        "detail_id": detail_id,
        "colors": colors,
        "captured": captured_color_texts(collector, detail_id),
        "overrides": overrides,
        "sources": preview_sources(current),
    }


def report(snapshot: dict) -> None:
    resolved = snapshot["resolved"]
    print(f"Product : {resolved.get('title')}")
    print(f"URL     : {resolved.get('permalink')}")
    print(f"Style   : {resolved.get('sku')}   post {resolved.get('post_id')}   "
          f"collector detail {snapshot['detail_id']}")
    print(f"Captured source colour text : {', '.join(snapshot['captured']) or '(none)'}")
    print("Published variants:")
    for color in snapshot["colors"]:
        value = str(color.get("value"))
        names = snapshot["sources"].get(value) or [swatch_source_text(color)]
        print(f"  - {value:8} label={color.get('label')!r}"
              f"  matched_on={', '.join(repr(name) for name in names)}"
              f"  image_id={color.get('image_id')}")
    if snapshot["overrides"]:
        print("Stored overrides:")
        for row in snapshot["overrides"]:
            print(f"  - id={row.get('id')} {row.get('dimension_name')} "
                  f"{row.get('source_text')!r} -> {row.get('display_label')!r}")
    else:
        print("Stored overrides: (none)")


def require_match(snapshot: dict, source: str) -> None:
    known = {normalize_text(value) for value in snapshot["captured"]}
    known |= {normalize_text(swatch_source_text(color)) for color in snapshot["colors"]}
    if normalize_text(source) not in known:
        die(f"{source!r} is not a colour on this product. Known values: "
            f"{sorted(value for value in known if value)}")


def command_inspect(client: Client, collector: Collector, args) -> int:
    report(state(client, collector, args.identifier))
    return 0


def command_apply(client: Client, collector: Collector, args) -> int:
    target = clean_label(args.label)
    if not target or len(target) > MAX_LABEL:
        die(f"--label must be 1 to {MAX_LABEL} characters")
    snapshot = state(client, collector, args.identifier)
    require_match(snapshot, args.source)
    payload, renamed = rename_payload(payload_for_sync(snapshot["resolved"]),
                                      args.source, target, snapshot["sources"])
    if not renamed:
        die(f"No published colour matches {args.source!r}.")
    print(f"Product : {snapshot['resolved'].get('title')}  ({snapshot['resolved'].get('sku')})")
    print(f"Rename  : {args.source!r} -> {target!r}  (colour values {', '.join(renamed)})")
    for color in snapshot["colors"]:
        if str(color.get("value")) in renamed:
            print(f"  - {color.get('value')}: {color.get('label')!r} -> {target!r}")
    if not args.apply:
        print("DRY RUN - nothing written. Re-run with --apply.")
        return 0

    saved = collector.request(
        "POST",
        f"/api/product-details/{snapshot['detail_id']}/option-overrides",
        {"sourceText": args.source, "displayLabel": target,
         "dimensionName": args.dimension, "note": args.note or ""},
    )
    print(f"Collector override saved: id={((saved or {}).get('override') or {}).get('id')}")

    client.request("POST", "/hx/v1/products/sync", data=payload)

    refreshed = resolve_wordpress(client, str(snapshot["resolved"].get("post_id")))
    labels = {str(c.get("value")): c.get("label")
              for c in (refreshed.get("catalog") or {}).get("colors", {}).get("colors") or []}
    print(f"WordPress now: {json.dumps(labels, ensure_ascii=False)}")

    if not args.no_verify:
        preview = preview_payload(collector, snapshot["detail_id"], refreshed)
        assert_preview_matches(preview, payload)
        print("Collector preview agrees with WordPress; later captures cannot revert this.")

    if args.purge_cache:
        subprocess.run([sys.executable, str(SKILL_DIR / "scripts" / "hostinger.py"),
                        "cache-purge"], check=False)
    return 0


def command_revert(client: Client, collector: Collector, args) -> int:
    snapshot = state(client, collector, args.identifier)
    matches = [row for row in snapshot["overrides"]
               if normalize_text(row.get("source_text")) == normalize_text(args.source)]
    if not matches:
        die(f"No stored override for {args.source!r}.")
    print("Overrides to remove:")
    for row in matches:
        print(f"  - id={row.get('id')} {row.get('source_text')!r} -> {row.get('display_label')!r}")
    if not args.apply:
        print("DRY RUN - nothing written. Re-run with --apply.")
        return 0

    for row in matches:
        collector.request(
            "DELETE",
            f"/api/product-details/{snapshot['detail_id']}/option-overrides/{row.get('id')}",
        )

    # The collector is the source of truth for the restored label.
    preview = preview_payload(collector, snapshot["detail_id"], snapshot["resolved"])
    labels = {str(c.get("value")): clean_label(c.get("label"))
              for c in (preview.get("colors") or {}).get("colors") or []}
    client.request("POST", "/hx/v1/products/sync", data=payload_for_sync(snapshot["resolved"], labels))
    print(f"Reverted; WordPress now: {json.dumps(labels, ensure_ascii=False)}")
    if args.purge_cache:
        subprocess.run([sys.executable, str(SKILL_DIR / "scripts" / "hostinger.py"),
                        "cache-purge"], check=False)
    return 0


def parser() -> argparse.ArgumentParser:
    root = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    root.add_argument("--config", help="Wearhongxiu config.env path")
    sub = root.add_subparsers(dest="command", required=True)

    for name, help_text in (("inspect", "Show the published variant labels and their sources"),
                            ("apply", "Record the override and correct WordPress"),
                            ("revert", "Remove the override and restore the captured label")):
        node = sub.add_parser(name, help=help_text)
        node.add_argument("identifier",
                          help="Style number, WordPress product URL, slug, or post ID")
        if name in {"apply", "revert"}:
            node.add_argument("--source", required=True,
                              help="The captured colour text to match, for example 9007")
            node.add_argument("--apply", action="store_true", help="Write the change")
            node.add_argument("--purge-cache", action="store_true",
                              help="Purge the Wearhongxiu cache after the write")
        if name == "apply":
            node.add_argument("--label", required=True, help="The corrected display name")
            node.add_argument("--dimension", default="color", help="Default: color")
            node.add_argument("--note", help="Why this label was chosen")
            node.add_argument("--no-verify", action="store_true",
                              help="Skip the collector preview cross-check")
    return root


def main() -> int:
    args = parser().parse_args()
    client = Client(config(args.config))
    collector = Collector()
    if args.command == "inspect":
        return command_inspect(client, collector, args)
    if args.command == "apply":
        return command_apply(client, collector, args)
    return command_revert(client, collector, args)


if __name__ == "__main__":
    raise SystemExit(main())
