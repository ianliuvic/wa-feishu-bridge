def coolify_env_value(key: str) -> str:
    """Read one collector environment value from Coolify without printing it."""
    path = Path.home() / ".coolify" / "config.json"
    if not path.exists():
        return ""
    cfg = json.loads(path.read_text(encoding="utf-8"))
    url = f"{cfg['base_url']}/applications/{COLLECTOR_APP_UUID}/envs"
    request = urllib.request.Request(
        url, headers={"Authorization": f"Bearer {cfg['token']}", "Accept": "application/json"}
    )
    for entry in json.load(urllib.request.urlopen(request, timeout=60)):
        if entry.get("key") == key and str(entry.get("value", "")).strip():
            return str(entry["value"]).strip()
    return ""


def collector_config() -> tuple[str, str]:
    # The harness scrubs KEY/TOKEN-shaped variables from shell commands, so on a
    # worker image the values come from the skill credential file instead.
    if _load_skill_credentials:
        _load_skill_credentials(*COLLECTOR_URL_KEYS, *COLLECTOR_KEY_KEYS)

    def first(keys) -> str:
        for key in keys:
            value = os.environ.get(key, "").strip()
            if value:
                return value
        return ""

    base = first(COLLECTOR_URL_KEYS)
    key = first(COLLECTOR_KEY_KEYS)
    if not (base and key):
        cfg = load_env(SKILL_DIR / "config.env")
        base = base or cfg.get("HONGXIU_COLLECTOR_API_URL", "").strip()
        key = key or cfg.get("HONGXIU_COLLECTOR_API_KEY", "").strip()
    if not base:
        base = COLLECTOR_DEFAULT_URL
    host = (urlparse(base).hostname or "").lower()
    if not host.endswith(COLLECTOR_ALLOWED_SUFFIX):
        die(f"Refusing to send the collector key to {host or base!r}")
    if not key:
        key = coolify_env_value("ADMIN_API_KEY")
    if not key:
        die("No collector key. Set HONGXIU_COLLECTOR_API_KEY or configure the collector app.")
    return base.rstrip("/"), key


class Collector:
    def __init__(self) -> None:
        self.base, self.key = collector_config()

    def request(self, method: str, path: str, body=None, timeout: int = 300):
        data = json.dumps(body).encode("utf-8") if body is not None else None
        request = urllib.request.Request(
            f"{self.base}{path}",
            data=data,
            method=method,
            headers={
                "Authorization": f"Bearer {self.key}",
                "Accept": "application/json",
                "Content-Type": "application/json",
                "User-Agent": USER_AGENT,
            },
        )
        try:
            with urllib.request.urlopen(request, timeout=timeout) as response:
                raw = response.read().decode("utf-8", "replace")
                return json.loads(raw) if raw else None
        except urllib.error.HTTPError as error:
            detail = error.read().decode("utf-8", "replace")
            try:
                detail = json.loads(detail)
            except ValueError:
                detail = detail[:400]
            die(f"collector {method} {path} -> HTTP {error.code}: {detail}")
        except urllib.error.URLError as error:
            die(f"cannot reach the collector at {self.base}: {error.reason}")


