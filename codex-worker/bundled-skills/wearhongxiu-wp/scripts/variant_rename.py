# The collector application whose environment holds the collector bearer key.
COLLECTOR_APP_UUID = "kc1izz5i6mnhs9z29ckl1ajp"
COLLECTOR_DEFAULT_URL = "https://collector.yiswim.cloud"
COLLECTOR_ALLOWED_SUFFIX = ".yiswim.cloud"
