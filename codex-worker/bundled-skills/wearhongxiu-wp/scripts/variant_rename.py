#!/usr/bin/env python3
"""Inspect and correct an unreasonable Wearhongxiu product variant label.

The colour label on a Wearhongxiu product is generated by the 1688 collector
from the captured source SKU options, so a bare merchant code such as `9007`
reaches the storefront, and editing WordPress alone is not durable: the next
capture, translation refresh, or swatch repair writes the code back.

This command owns both halves of the fix:

1. it records a manual display-name override on the collector product, which is
   what makes the corrected name survive later captures and repairs; and
2. it writes the corrected labels into the live WordPress product through the
   authenticated `hx/v1` product sync, without re-uploading any media.

Nothing is written without `--apply`. Read references/variant-rename.md before
using it.
"""

