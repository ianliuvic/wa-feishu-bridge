def resolver_params(identifier: str) -> dict[str, str]:
    if identifier.isdigit():
        return {"post_id": identifier}
    if identifier.startswith("https://"):
        host = (urlparse(identifier).hostname or "").lower()
        if host not in {"wearhongxiu.com", "www.wearhongxiu.com"}:
            die(f"Off-site product URL is not allowed: {identifier}")
        return {"url": identifier}
    if re.fullmatch(r"[A-Za-z0-9_-]{2,40}", identifier):
        return {"style_no": identifier}
    return {"slug": identifier}


def resolve_wordpress(client: Client, identifier: str) -> dict:
    params = resolver_params(identifier)
    try:
        resolved, _ = client.request("GET", "/hx/v1/products/resolve", params=params)
    except ApiError:
        if "style_no" not in params:
            raise
        resolved, _ = client.request("GET", "/hx/v1/products/resolve", params={"slug": identifier})
    return resolved


def collector_product(collector: Collector, style_no: str) -> dict:
    if not style_no:
        die("The WordPress product has no style number, so the collector source cannot be resolved.")
    resolved = collector.request(
        "GET", f"/api/wordpress/products/resolve?{urllib.parse.urlencode({'styleNo': style_no})}"
    )
    entry = (resolved or {}).get("collector") or {}
    if not entry.get("product_detail_id"):
        die(
            f"{style_no} has no collector source, so an override cannot be stored. "
            "This product is not collector-managed."
        )
    return entry


def captured_color_texts(collector: Collector, detail_id) -> list[str]:
    detail = collector.request("GET", f"/api/product-details/{detail_id}") or {}
    values: list[str] = []
    for sku in detail.get("skus") or []:
        for key, value in (sku.get("option_data") or {}).items():
            if normalize_text(key) in COLOR_KEYS and clean_label(value):
                if clean_label(value) not in values:
                    values.append(clean_label(value))
    return values


# --------------------------------------------------------------------------- #
# Label mapping, mirroring the collector's own override rules
# --------------------------------------------------------------------------- #


def swatch_source_text(color: dict) -> str:
    return clean_label(color.get("source_label") or color.get("label"))


def preview_sources(preview: dict) -> dict[str, list[str]]:
    """Colour value -> every text that identifies that colour.

    A colour can be named by its corrected label, by the translated option the
    collector publishes, or by the raw captured 1688 text, and the operator may
    use any of them. The SKU matrix is what links a published label to its
    captured source text.
    """
    raw_by_display: dict[str, set[str]] = {}
    for row in (preview.get("sku_matrix") or {}).get("rows") or []:
        raw = [clean_label(value) for key, value in (row.get("source_options") or {}).items()
               if normalize_text(key) in COLOR_KEYS]
        displays = [clean_label(row.get("color"))]
        displays += [clean_label(value) for key, value in (row.get("options") or {}).items()
                     if normalize_text(key) in COLOR_KEYS]
        for display in displays:
            if display:
                raw_by_display.setdefault(normalize_text(display), set()).update(filter(None, raw))

    sources: dict[str, list[str]] = {}
    for color in (preview.get("colors") or {}).get("colors") or []:
        identifiers = {swatch_source_text(color), clean_label(color.get("label"))}
        identifiers = {value for value in identifiers if value}
        captured: set[str] = set()
        for identifier in identifiers:
            captured |= raw_by_display.get(normalize_text(identifier), set())
        sources[str(color.get("value"))] = sorted(identifiers | captured)
    return sources


def matching_keys(sources: dict[str, list[str]] | None, value: str, color: dict) -> set[str]:
    keys = {normalize_text(swatch_source_text(color)), normalize_text(color.get("label"))}
    keys |= {normalize_text(item) for item in (sources or {}).get(str(value)) or []}
    return {key for key in keys if key}


def rename_payload(payload: dict, source: str, target: str,
                   sources: dict[str, list[str]] | None = None) -> tuple[dict, list[str]]:
    """Return the synced payload plus the colour values that were renamed.

    Matching uses the explicit `source_label` provenance, the texts the
    collector associates with that colour, and the published label. That lets an
    already-corrected product be renamed again even though its storefront label
    no longer shows the captured code.
    """
    updated = copy.deepcopy(payload)
    key = normalize_text(source)
    renamed: list[str] = []

    for color in (updated.get("colors") or {}).get("colors") or []:
        value = str(color.get("value"))
        if key not in matching_keys(sources, value, color):
            continue
        color["source_label"] = clean_label(color.get("source_label") or source)
        color["label"] = target
        renamed.append(value)

    for row in (updated.get("sku_matrix") or {}).get("rows") or []:
        options = row.get("options") or {}
        source_options = row.get("source_options") or {}
        values = [row.get("color"),
                  *[v for k, v in options.items() if normalize_text(k) in COLOR_KEYS],
                  *[v for k, v in source_options.items() if normalize_text(k) in COLOR_KEYS]]
        if not any(normalize_text(value) == key for value in values):
            continue
        for option_key in list(options):
            if normalize_text(option_key) in COLOR_KEYS:
                options[option_key] = target
        if normalize_text(row.get("color")) == key:
            row["color"] = target

    return updated, renamed


def payload_for_sync(resolved: dict, labels: dict | None = None) -> dict:
    """Build the exact payload the `hx/v1/products/sync` route requires.

    That route rewrites title, description, status, and every meta key it is
    given, so the resolver snapshot is replayed in full; categories, tags, and
    images are omitted so the live terms, gallery, and featured image stay
    untouched.
    """
    meta = dict(resolved.get("meta") or {})
    payload = {
        "external_id": resolved.get("external_id"),
        "style_no": resolved.get("sku"),
        "title": resolved.get("title"),
        "description": meta.get("description", ""),
        "status": resolved.get("status") or "publish",
        "meta": meta,
        "colors": resolved.get("catalog", {}).get("colors"),
        "sku_matrix": resolved.get("catalog", {}).get("sku_matrix"),
    }
    for color in (payload.get("colors") or {}).get("colors") or []:
        target = (labels or {}).get(str(color.get("value")))
        if target and target != color.get("label"):
            color["source_label"] = clean_label(color.get("source_label") or color.get("label"))
            color["label"] = target
    return payload


def preview_payload(collector: Collector, detail_id, resolved: dict) -> dict:
    """Ask the collector what it would publish now, without a model call."""
    meta = resolved.get("meta") or {}
    categories = [c.get("id") for c in resolved.get("categories") or [] if c.get("id")]
    tags = [t.get("name") for t in resolved.get("tags") or [] if t.get("name")]
    primary = meta.get("primary_category_id") or (categories[0] if categories else None)
    body = {
        "status": resolved.get("status") or "publish",
        "styleNo": resolved.get("sku"),
        "categoryIds": categories,
        "primaryCategoryId": int(primary) if str(primary or "").isdigit() else None,
        "categoryMode": "manual",
        "tagMode": "manual",
        "tags": tags,
        "material": meta.get("material") or "Polyester",
    }
    body = {key: value for key, value in body.items() if value not in (None, [], "")}
    result = collector.request("POST", f"/api/product-details/{detail_id}/wordpress/preview", body)
    return (result or {}).get("payload") or {}


def assert_preview_matches(preview: dict, payload: dict) -> None:
    expected = {str(c.get("value")): clean_label(c.get("label"))
                for c in (payload.get("colors") or {}).get("colors") or []}
    actual = {str(c.get("value")): clean_label(c.get("label"))
              for c in (preview.get("colors") or {}).get("colors") or []}
    if expected != actual:
        die(f"The collector would publish {actual} but WordPress was set to {expected}.")
    expected_rows = {r.get("source_sku_key"): clean_label(r.get("color"))
                     for r in (payload.get("sku_matrix") or {}).get("rows") or []}
    actual_rows = {r.get("source_sku_key"): clean_label(r.get("color"))
                   for r in (preview.get("sku_matrix") or {}).get("rows") or []}
    if expected_rows != actual_rows:
        die(f"The collector SKU matrix disagrees with WordPress: {actual_rows} vs {expected_rows}.")


